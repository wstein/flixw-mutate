package dev.flixw.mutate;

/**
 * The Flix side of the solver hook: a module that is compiled with the program and called from the patched
 * {@code Fixpoint3.Solver.runSolverInternal} through {@link Splice}. For every solve of the program it writes JVM
 * system properties, which {@link DatalogState} reads and clears around each test:
 * <pre>
 *   flixw.dl.solves          the number of solves since the last reset
 *   flixw.dl.N.rules         the count of rules of solve N; flixw.dl.N.rule.I  the signature of rule I
 *   flixw.dl.N.facts         the count of facts of solve N; flixw.dl.N.fact.J  the text of fact J
 * </pre>
 * A rule signature is {@code Head<-Body1,Body2}: the predicate names of the head and the body atoms (guards and
 * functionals left out). A fact is a constraint without a body, printed {@code Name(t1, t2).}; a literal is printed
 * with its {@code ToString}, a term that is not a literal as {@code <function>}. A solve whose rules are all
 * {@code $Result} rules is a query over a model: it is not a solve of the program and is not recorded. A query over a
 * constraint set ({@code query p select ...}) has the rules of the set and one {@code $Result} rule: it is recorded.
 * A solve with no rule at all (a set of facts only) is recorded. A {@code query} directly over a set of facts only has
 * the {@code $Result} rule alone and cannot be told from a query over a model: it is not recorded.
 * The module names Fixpoint3 internals (checked on Flix 0.79.0 only).
 */
final class DatalogHook {
    static final String FILE = "FlixwDatalog.flix";

    private DatalogHook() { }

    /** The module as Flix source. */
    static String source() {
        return """
            // Generated by flixw-mutate: the solver hook that records which rules and facts a test solves.
            mod FlixwDatalog {
                import java.lang.System

                ///
                /// Called with the Datalog value that enters the solver. Returns the number of solves so far (0: nothing recorded).
                /// `@DontInline` and a used result keep the function in the compiled program.
                ///
                @DontInline
                pub def flixwHit(d: Fixpoint3.Ast.Datalog.Datalog): Int32 = match fwInput(d) {
                    case None => 0
                    case Some((facts, rules)) =>
                        if (fwOnlyResult(rules)) 0
                        else {
                            let n = fwGetInt("flixw.dl.solves");
                            let t1 = fwSet("flixw.dl.solves", "${n + 1}");
                            let t2 = fwSet("flixw.dl.${n}.rules", "${Vector.length(rules)}");
                            let t3 = fwSet("flixw.dl.${n}.facts", "${Vector.length(facts)}");
                            let t4 = Vector.mapWithIndex((i, c) -> fwSet("flixw.dl.${n}.rule.${i}", fwSig(c)), rules);
                            let t5 = Vector.mapWithIndex((i, c) -> fwSet("flixw.dl.${n}.fact.${i}", fwText(c)), facts);
                            let used = t1 + t2 + t3 + Vector.foldLeft((a, b) -> a + b, 0, t4) + Vector.foldLeft((a, b) -> a + b, 0, t5);
                            if (used < 0) bug!("flixw-datalog") else n + 1
                        }
                }

                def fwInput(d: Fixpoint3.Ast.Datalog.Datalog): Option[(Vector[Fixpoint3.Ast.Datalog.Constraint], Vector[Fixpoint3.Ast.Datalog.Constraint])] = match d {
                    case Fixpoint3.Ast.Datalog.Datalog.Datalog(f, r) => Some((f, r))
                    case Fixpoint3.Ast.Datalog.Datalog.Join(_, b) => fwInput(b)
                    case _ => None
                }

                def fwOnlyResult(rules: Vector[Fixpoint3.Ast.Datalog.Constraint]): Bool =
                    Vector.length(rules) > 0 and Vector.forAll(match Fixpoint3.Ast.Datalog.Constraint.Constraint(Fixpoint3.Ast.Datalog.HeadPredicate.HeadAtom(Fixpoint3.Ast.Shared.PredSym.PredSym(name, _), _, _), _) -> name == "$Result", rules)

                def fwText(c: Fixpoint3.Ast.Datalog.Constraint): String = match c {
                    case Fixpoint3.Ast.Datalog.Constraint.Constraint(h, _) => "${fwHead(h)}."
                }

                def fwHead(h: Fixpoint3.Ast.Datalog.HeadPredicate): String = match h {
                    case Fixpoint3.Ast.Datalog.HeadPredicate.HeadAtom(Fixpoint3.Ast.Shared.PredSym.PredSym(name, _), _, terms) =>
                        "${name}(${terms |> Vector.map(fwTerm) |> Vector.join(", ")})"
                }

                def fwTerm(t: Fixpoint3.Ast.Datalog.HeadTerm): String = match t {
                    case Fixpoint3.Ast.Datalog.HeadTerm.Lit(v) => "${v}"
                    case Fixpoint3.Ast.Datalog.HeadTerm.Var(v) => "${v}"
                    case _ => "<function>"
                }

                def fwSig(c: Fixpoint3.Ast.Datalog.Constraint): String = match c {
                    case Fixpoint3.Ast.Datalog.Constraint.Constraint(Fixpoint3.Ast.Datalog.HeadPredicate.HeadAtom(Fixpoint3.Ast.Shared.PredSym.PredSym(h, _), _, _), body) =>
                        "${h}<-${body |> Vector.filterMap(fwBodyName) |> Vector.join(",")}"
                }

                def fwBodyName(b: Fixpoint3.Ast.Datalog.BodyPredicate): Option[String] = match b {
                    case Fixpoint3.Ast.Datalog.BodyPredicate.BodyAtom(Fixpoint3.Ast.Shared.PredSym.PredSym(n, _), _, _, _, _) => Some(n)
                    case _ => None
                }

                def fwSet(key: String, value: String): Int32 = unsafe IO {
                    let _ = System.setProperty(key, value);
                    0
                }

                def fwGetInt(key: String): Int32 =
                    Int32.fromString(unsafe IO { System.getProperty(key, "0") }) |> Option.getWithDefault(0)

                ///
                /// Keeps `flixwHit` in the compiled program (tree shaking drops what no test or main reaches). The engine does not run it as a test.
                ///
                @Test
                def keepHook(): Unit \\ Assert =
                    Assert.assertEq(expected = 1, flixwHit(Fixpoint3.Ast.Datalog.Datalog.Datalog(Vector#{}, Vector#{})))
            }
            """;
    }
}
