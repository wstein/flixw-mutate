package dev.flixw.mutate;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

/** Renders mutant schemata: the sites of a file become calls into the switch module {@code FlixwMutant}. */
public final class Schemata {
    private Schemata() { }

    /** The rewritten file and the mutants its sites carry (ids from {@code firstId}, consecutive). */
    public record Rendered(String text, List<Mutant> mutants) {}

    /** The switch module {@code FlixwMutant} as Flix source. */
    public static String module() {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by flixw-mutate. The switch and the coverage marker are dev.flixw.mutate.Marker (mutant 0: none).\n");
        sb.append("mod FlixwMutant {\n    import dev.flixw.mutate.Marker\n\n");
        sb.append("    pub def on(n: Int32): Bool = unsafe IO { Marker.on(n) }\n");
        for (SiteKind k : SiteKind.values()) {
            sb.append('\n');
            String o = k.operator();
            List<String> m = k.mutations();
            String second = m.size() == 2 ? "n1: Int32, n2: Int32" : "n1: Int32";
            switch (k.shape()) {
                case COMPARE, ARITHMETIC -> {
                    String ret = k.shape() == SiteKind.Shape.COMPARE ? "Bool" : "t";
                    sb.append("    pub def ").append(k.helper()).append('(').append(second).append(", x: t, y: t): ")
                        .append(ret).append(" with ").append(constraints(k)).append(" =\n        ");
                    sb.append("if (on(n1)) x ").append(m.get(0)).append(" y");
                    if (m.size() == 2) sb.append(" else if (on(n2)) x ").append(m.get(1)).append(" y");
                    sb.append(" else x ").append(o).append(" y\n");
                }
                case LAZY -> {
                    sb.append("    pub def ").append(k.helper()).append("(n1: Int32, a: Bool, b: Unit -> Bool \\ ef): Bool \\ ef =\n");
                    sb.append("        if (on(n1)) a ").append(m.get(0)).append(" b() else a ").append(o).append(" b()\n");
                }
                case NEGATION -> {
                    sb.append("    pub def ").append(k.helper()).append("(n1: Int32, b: Bool): Bool =\n");
                    sb.append("        if (on(n1)) not b else b\n");
                }
            }
        }
        sb.append("}\n");
        return sb.toString();
    }

    private static String constraints(SiteKind k) {
        return switch (k) {
            case LESS, LESS_EQUAL, GREATER, GREATER_EQUAL -> "Order[t]";
            case EQUAL, NOT_EQUAL -> "Eq[t]";
            case ADD -> "Add[t], Sub[t]";
            case SUBTRACT -> "Sub[t], Add[t]";
            case MULTIPLY -> "Mul[t], Div[t]";
            case DIVIDE -> "Div[t], Mul[t]";
            default -> throw new IllegalArgumentException(k.toString());
        };
    }

    /** A site with the sites nested in its operands. */
    private static final class Node {
        final Site site;
        int id;
        final List<Node> kids = new ArrayList<>();

        Node(Site site) { this.site = site; }
    }

    /**
     * Rewrites {@code source}. Sites may nest only inside the operands of another site; anything else
     * (partial overlap, a site in the operator text) is an {@link IllegalArgumentException}.
     */
    public static Rendered render(String source, List<Site> sites, int firstId) {
        List<Node> sorted = new ArrayList<>();
        for (Site s : sites) {
            if (s.whole().end() > source.length()) throw new IllegalArgumentException("site beyond the end of the text");
            sorted.add(new Node(s));
        }
        sorted.sort(Comparator.<Node>comparingInt(n -> n.site.whole().start())
            .thenComparing(n -> -n.site.whole().end()));
        List<Node> roots = new ArrayList<>();
        List<Node> open = new ArrayList<>();
        List<Mutant> mutants = new ArrayList<>();
        int next = firstId;
        for (Node n : sorted) {
            Span w = n.site.whole();
            while (!open.isEmpty() && open.get(open.size() - 1).site.whole().end() <= w.start()) open.remove(open.size() - 1);
            if (open.isEmpty()) {
                roots.add(n);
            } else {
                Node parent = open.get(open.size() - 1);
                if (!parent.site.whole().contains(w)) throw new IllegalArgumentException("sites overlap: " + parent.site + " and " + n.site);
                if (!inOperand(parent.site, w)) throw new IllegalArgumentException("site outside the operands of " + parent.site);
                parent.kids.add(n);
            }
            open.add(n);
            n.id = next;
            for (String to : n.site.kind().mutations()) mutants.add(new Mutant(next++, n.site, n.site.kind().operator(), to));
        }
        return new Rendered(slice(source, 0, source.length(), roots), mutants);
    }

    private static boolean inOperand(Site s, Span inner) {
        return s.left().contains(inner) || (s.right() != null && s.right().contains(inner));
    }

    /** The text of the range with the nodes (sorted, disjoint, inside the range) rewritten. */
    private static String slice(String source, int start, int end, List<Node> nodes) {
        StringBuilder sb = new StringBuilder();
        int pos = start;
        for (Node n : nodes) {
            sb.append(source, pos, n.site.whole().start());
            sb.append(rewrite(source, n));
            pos = n.site.whole().end();
        }
        sb.append(source, pos, end);
        return sb.toString();
    }

    private static String operand(String source, Span span, Node node) {
        List<Node> inside = new ArrayList<>();
        for (Node k : node.kids) if (span.contains(k.site.whole())) inside.add(k);
        return slice(source, span.start(), span.end(), inside);
    }

    private static String rewrite(String source, Node n) {
        Site s = n.site;
        SiteKind k = s.kind();
        String ids = n.id + (k.mutations().size() == 2 ? ", " + (n.id + 1) : "");
        String head = "(FlixwMutant." + k.helper() + "(" + ids + ", ";
        return switch (k.shape()) {
            case COMPARE, ARITHMETIC ->
                head + "(" + operand(source, s.left(), n) + "), (" + operand(source, s.right(), n) + ")))";
            case LAZY ->
                head + "(" + operand(source, s.left(), n) + "), () -> (" + operand(source, s.right(), n) + ")))";
            case NEGATION -> head + operand(source, s.whole(), n) + "))";
        };
    }

    /**
     * The sites {@link #render} accepts: a site that overlaps another one without being inside one of
     * its operands is left out (the outer site wins), so is a duplicate. The order of the result is the
     * order of the rewrite (start ascending, longer first).
     */
    public static List<Site> usable(List<Site> sites) {
        List<Site> sorted = new ArrayList<>(sites);
        sorted.sort(Comparator.<Site>comparingInt(x -> x.whole().start()).thenComparing(x -> -x.whole().end()));
        List<Site> kept = new ArrayList<>();
        List<Site> open = new ArrayList<>();
        for (Site s : sorted) {
            Span w = s.whole();
            while (!open.isEmpty() && open.get(open.size() - 1).whole().end() <= w.start()) open.remove(open.size() - 1);
            if (!open.isEmpty()) {
                Site parent = open.get(open.size() - 1);
                if (!parent.whole().contains(w) || !inOperand(parent, w)) continue;
            }
            kept.add(s);
            open.add(s);
        }
        return kept;
    }

    /** 1-based line and column of an offset, as {@code line:col}. */
    public static String position(String source, int offset) {
        int line = 1;
        int lineStart = 0;
        for (int i = 0; i < offset && i < source.length(); i++) {
            if (source.charAt(i) == '\n') {
                line++;
                lineStart = i + 1;
            }
        }
        return line + ":" + (offset - lineStart + 1);
    }
}
